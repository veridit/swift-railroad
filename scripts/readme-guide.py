#!/usr/bin/env python3
"""Regenerate the README's visual guide from VocabularyTests.swift.

Each entry shows the reference SVG (Tests/RailroadTests/Fixtures/vocabulary),
its caption (the SVG's <title>), and the Swift code from the test that renders
that exact SVG byte for byte. So the guide cannot show code that does not
produce the picture.

    scripts/readme-guide.py          rewrite README.md in place
    scripts/readme-guide.py --check  exit 1 if README.md is out of date
"""
import html, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TESTS = ROOT / "Tests/RailroadTests/VocabularyTests.swift"
FIXTURES = "Tests/RailroadTests/Fixtures/vocabulary"
README = ROOT / "README.md"
BEGIN, END = "<!-- guide:begin -->", "<!-- guide:end -->"

GROUPS = [
    ("Tokens", ["terminal", "nonterminal", "comment", "link"]),
    ("Sequences and choices", ["sequence", "stack", "choice", "multi-choice", "empty", "subsequence"]),
    ("Repetition", ["optional", "one-or-more", "zero-or-more", "separated-list"]),
    ("Boxes and annotations", ["labeled-box", "annotation", "negative-lookahead", "negative-lookbehind", "scale"]),
    ("Start, end and continuation", ["start-end", "simple-start-end", "continuation", "continuation-start-end"]),
    ("Layout", ["vertical-grid", "horizontal-grid", "alignment", "aligned-rule-labels"]),
]
HELPERS = ("t(", "nt(", "c(")


def test_bodies():
    src = TESTS.read_text()
    bodies = {}
    for m in re.finditer(r"func test\w+\(\) throws \{\n(.*?)\n    \}\n", src, re.S):
        body = m.group(1)
        slug = re.search(r'try check\("([^"]+)"', body).group(1)
        lines = [l[8:] if l.startswith("        ") else l.strip() for l in body.split("\n")]
        code = "\n".join(lines)
        # `try check("slug", NODE[, bare: true])` -> `let diagram = NODE`
        code = re.sub(r'try check\("[^"]+", ', "let node = ", code)
        code = re.sub(r"(, bare: true)?\)\s*$", "", code)
        bodies[slug] = code
    return bodies


def caption(slug):
    svg = (ROOT / FIXTURES / f"{slug}.svg").read_text()
    text = re.search(r"<title>\n(.*?)</title>", svg, re.S).group(1).strip()
    return html.unescape(text)


def guide():
    bodies = test_bodies()
    listed = [s for _, slugs in GROUPS for s in slugs]
    missing = sorted(set(bodies) - set(listed))
    if missing:
        sys.exit(f"readme-guide: add these vocabulary tests to GROUPS: {missing}")
    out = [BEGIN,
           "<!-- Generated by scripts/readme-guide.py from VocabularyTests.swift. Do not edit by hand. -->",
           "",
           "Every picture below is a reference SVG from the Rust crate. The code under it is the",
           "test that renders that SVG byte for byte, so what you see is what the code produces.",
           "`t`, `nt` and `c` are shorthands for `RailroadTerminal(label:)`,",
           "`RailroadNonTerminal(label:)` and `RailroadComment(text:)`. Most diagrams are drawn",
           "between `RailroadSimpleStart()` and `RailroadSimpleEnd()`, as the crate's README does.",
           ""]
    for group, slugs in GROUPS:
        out += [f"### {group}", ""]
        for slug in slugs:
            out += [f"#### `{slug}`", "",
                    f"![{slug}]({FIXTURES}/{slug}.svg)", "",
                    caption(slug), "",
                    "```swift", bodies[slug], "```", ""]
    out.append(END)
    return "\n".join(out)


def main():
    text = README.read_text()
    new_guide = guide()
    if BEGIN in text:
        new = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: new_guide, text, flags=re.S)
    else:
        new = text.replace("## Themes", "## Visual guide\n\n" + new_guide + "\n\n## Themes", 1)
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md visual guide is out of date: run scripts/readme-guide.py")
        print("README.md visual guide is up to date")
        return
    README.write_text(new)
    print(f"README.md: {sum(len(s) for _, s in GROUPS)} entries")


main()
